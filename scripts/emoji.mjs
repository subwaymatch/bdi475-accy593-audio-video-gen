#!/usr/bin/env node
// Downloads Noto Animated Emoji (Google, CC BY 4.0 — https://googlefonts.github.io/noto-emoji-animation/)
// as Lottie JSON and bundles them into video/assets/emoji/emoji-data.js, so renders need no network.
//
// Usage: node scripts/emoji.mjs
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const EMOJI = {
  partying: "1f973", notes: "1f3b6", books: "1f4da", sparkles: "2728", grin: "1f601", raised_hands: "1f64c",
  fire: "1f525", rainbow: "1f308", heart: "1f496", star_struck: "1f929", wave: "1f44b", glowing_star: "1f31f",
  chart: "1f4ca", cool: "1f60e", clover: "1f340", rocket: "1f680", globe: "1f30d", grad_cap: "1f393",
  party_popper: "1f389", confetti_ball: "1f38a",
};

const data = {};
for (const [name, cp] of Object.entries(EMOJI)) {
  const res = await fetch(`https://fonts.gstatic.com/s/e/notoemoji/latest/${cp}/lottie.json`);
  if (!res.ok) throw new Error(`${name} (${cp}): HTTP ${res.status}`);
  data[name] = await res.json();
  console.log(`${name} ${cp}`);
}
const dir = path.join(ROOT, "video/assets/emoji");
await mkdir(dir, { recursive: true });
await writeFile(
  path.join(dir, "emoji-data.js"),
  "// Noto Animated Emoji by Google, CC BY 4.0 (https://googlefonts.github.io/noto-emoji-animation/).\n" +
    "// Generated by scripts/emoji.mjs — do not edit by hand.\n" +
    `window.EMOJI = ${JSON.stringify(data)};\n`
);
console.log(`wrote ${Object.keys(data).length} emoji`);
